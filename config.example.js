/* =========================================================
   config.example.js · 配置说明（本地版）
   这是 .env.example 在这类项目里的等价物：本文件不会被加载，
   也不要把它重命名成 config.js 放回去 —— 生效的配置只有一处，
   就是 index.html 里 <script> 中的 window.APP_CONFIG。
   ========================================================= */

/* 用法：改 index.html 里 <script> 中的那一段 window.APP_CONFIG，保存，刷新页面。
   「数据」页的提醒卡里也能改推送与阈值 —— 那一部分存在浏览器里，优先级更高，
   只有它在页面上留空时，才回落到这里写的值。 */

window.APP_CONFIG_EXAMPLE = {
  /* 时区。留空 = 跟着设备时区走；填了就以它为准：提醒的「今天 / 本月 / 每天几点之后」
     都按这个时区判定，发送日志的时间戳也按它显示。记账日期本身仍跟着设备日历。
     要写 IANA 格式（Asia/Shanghai、Europe/Berlin…），写错会被忽略并回落，不报错。
     优先级：这一行 > 「数据」页里选的 > 设备时区 > Asia/Shanghai */
  APP_TIMEZONE: "Asia/Shanghai",

  /* ---------- 日常轻提醒（今日支出达到今日预算的百分比时推到手机） ----------
     总开关。留空 = 由「数据」页上的开关决定；填 "false" 是部署级硬关，
     页面上怎么拧都不会出网。填 "true"/"1"/"on"/"yes" 等同于开。 */
  ENABLE_DAILY_BUDGET_PUSH: "true",

  /* 阈值，逗号分隔。默认 80 和 100 各推一次；
     写 "50,80,100" 就多一档。脏值（0、负数、超过 300、重复）会被丢掉并用默认。 */
  BUDGET_ALERT_THRESHOLDS: "80,100",

  /* 记完一笔账要不要立刻重算一次（防抖 400ms，异步，不挡录入）。
     留空 = 要；填 "false" = 只在打开页面和每天到点时算 —— 连着补记几十笔的人可能会想要这个。 */
  BUDGET_PUSH_ON_WRITE: "",

  /* 二选一："ntfy" 或 "pushover"。留空 = 这条通道不存在，一次请求都不会发。
     ntfy 是浏览器能直连的那个（跨源已放开）；Pushover 的 API 没有给浏览器开跨源，
     本地版这一条通常只能以一条失败日志收场，要真用它得走后端。 */
  PUSH_CHANNEL: "ntfy",

  /* ntfy：只要一个 topic 名，不需要任何密钥。
     NTFY_BASE_URL 留空 = 公共的 https://ntfy.sh；自建就填自己的地址。
     公共档大约 250 条/天、单条 4096 字节，够提醒用。
     注意：topic 是公开路由，知道名字的人都能订阅 —— 所以推送内容只有一句
     「今日支出 ¥xx，已用今日预算的 80%」，不含分类、备注、流水明细。 */
  NTFY_BASE_URL: "",
  NTFY_TOPIC: "pick-a-random-name-here",

  /* Pushover：这两个是密钥，不该出现在一个纯本地文件里。
     放在这一行 = 明文存在这台电脑上，任何能读到这个目录的人或程序都能拿走。
     真要用，请自建一个转发用的后端，把密钥留在后端的环境变量里，
     本地版只调用那个后端 —— 而不是把 app token 抄进浏览器。 */
  PUSHOVER_TOKEN: "",
  PUSHOVER_USER_KEY: ""
};

/* 关于密钥：本工具默认没有任何出网通道 —— 不发 fetch、不加载 CDN，
   数据 100% 留在浏览器 localStorage。上面这些键全部留空时，仍然是这样。
   一旦填了 topic 并打开「手机推送」，就会有那一条提醒文字离开这台设备，
   「数据」页的隐私卡会据实改掉「无联网 / 0 次网络请求」那句话。
   邮件通道（channels.email）依旧只有接口：浏览器不能直连 SMTP，
   也不该把授权码放进浏览器；接后端时密钥放后端的环境变量里。 */

